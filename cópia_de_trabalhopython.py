"""**PARTE 2: PRODUTIVIDADE OPERACIONAL**"""

# PASSO 1: IMPORTAR AS BIBLIOTECAS
import pandas as pd
import matplotlib.pyplot as plt


# PASSO 2: LER A PLANILHA
dados = pd.read_csv("Manufacturing Dataset.csv")


# PASSO 3: CALCULAR A PRODUTIVIDADE
dados["Produtividade"] = (
    dados["Units Produced"] / dados["Production Time Hours"]
)

# Mostrar as primeiras linhas da planilha com os dados.
print("PRIMEIRAS LINHAS DA PLANILHA:")
print(dados.head().to_string(index=False))

# PASSO 4: PRODUÇÃO TOTAL POR MÁQUINA

# Agrupar os dados pelo identificador da máquina.
producao_maquina = dados.groupby("Machine ID")[
    "Units Produced"
].sum().sort_values(ascending=False)

# Renomear os dados para exibir os resultados em português.
producao_maquina.index.name = "Identificação da máquina"
producao_maquina.name = "Total de unidades produzidas"

print("\nPRODUÇÃO TOTAL POR MÁQUINA:")
print(producao_maquina.to_string())

# Gráfico de barras da produção total por máquina.
producao_maquina.plot(kind="bar", figsize=(9, 4))

plt.title("Produção total por máquina")
plt.xlabel("Identificação da máquina")
plt.ylabel("Total de unidades produzidas")
plt.tight_layout()
plt.show()

# PASSO 5: PRODUÇÃO E PRODUTIVIDADE POR TURNO

# Agrupar os dados por turno.
turnos = dados.groupby("Shift").agg(
    Producao=("Units Produced", "sum"),
    Horas=("Production Time Hours", "sum")
)

# Calcular a produtividade de cada turno.
turnos["Produtividade"] = turnos["Producao"] / turnos["Horas"]

turnos = turnos.rename(index={
    "Day": "Diurno",
    "Swing": "Intermediário",
    "Night": "Noturno"
})

turnos = turnos.rename(columns={
    "Producao": "Produção total",
    "Horas": "Horas de produção",
    "Produtividade": "Produtividade (unidades por hora)"
})

print("\nPRODUÇÃO E PRODUTIVIDADE POR TURNO:")
print(turnos.round(2).to_string())

# Gráfico da produtividade por turno.
turnos["Produtividade (unidades por hora)"].plot(
    kind="bar", figsize=(7, 4)
)

plt.title("Produtividade por turno")
plt.xlabel("Turno de trabalho")
plt.ylabel("Unidades produzidas por hora")
plt.tight_layout()
plt.show()

# PASSO 6: PRODUTIVIDADE POR MÁQUINA

# Agrupar os dados por máquina.
maquinas = dados.groupby("Machine ID").agg(
    Producao=("Units Produced", "sum"),
    Horas=("Production Time Hours", "sum")
)

# Calcular a produtividade total de cada máquina.
maquinas["Produtividade"] = (
    maquinas["Producao"] / maquinas["Horas"]
)

# Organizar as máquinas da mais produtiva para a menos produtiva
maquinas = maquinas.sort_values(
    "Produtividade", ascending=False
)

# Exibir somente as cinco máquinas mais produtivas.
cinco_maquinas = maquinas["Produtividade"].head().round(2)

cinco_maquinas.index.name = "Identificação da máquina"
cinco_maquinas.name = "Produtividade (unidades por hora)"

print("\nCINCO MÁQUINAS MAIS PRODUTIVAS:")
print(cinco_maquinas.to_string())

# Gráfico da produtividade de todas as máquinas.
maquinas["Produtividade"].sort_values().plot(
    kind="bar", figsize=(9, 4)
)

plt.title("Produtividade por máquina")
plt.xlabel("Identificação da máquina")
plt.ylabel("Unidades produzidas por hora")
plt.tight_layout()
plt.show()

# PASSO 7: QUANTIDADE DE OPERADORES E PRODUTIVIDADE

# Agrupar os registros pela quantidade de operadores.
operadores = dados.groupby("Operator Count")[
    "Produtividade"
].mean()

# Ordenar os resultados pela quantidade de operadores.
operadores = operadores.sort_index()

operadores.index.name = "Quantidade de operadores"
operadores.name = "Produtividade média (unidades por hora)"

print("\nPRODUTIVIDADE MÉDIA POR QUANTIDADE DE OPERADORES:")
print(operadores.round(2).to_string())

# Gráfico para comparar a produtividade média
operadores.plot(kind="bar", figsize=(7, 4))

plt.title("Quantidade de operadores e produtividade")
plt.xlabel("Quantidade de operadores")
plt.ylabel("Produtividade média (unidades por hora)")
plt.tight_layout()
plt.show()